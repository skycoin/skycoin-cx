// objmodelgenTagOnlyObjects are Gid types with a tag and a name in the table
// but a hand written manager, such as the string pool and the source files
// of #413.
var objmodelgenTagOnlyObjects = []objmodelgenObject{
	{Obj: "String", TypeTag: 0x0F},
	{Obj: "SourceFile", TypeTag: 0x10},
}

// objmodelgenHeader starts every generated file, and -check finds stale
// generated files by it.
const objmodelgenHeader = "// Code generated by t0-cx-core-objmodelgen. DO NOT EDIT.\n\n"

// objmodelgenFileName is <obj>, the type name lower case without underscores.
func objmodelgenFileName(obj string) string {
	return strings.ToLower(strings.ReplaceAll(obj, "_", ""))
}

func objmodelgenRender(tmpl *template.Template, name string, object objmodelgenObject) ([]byte, error) {
	other := 0x01
	if object.TypeTag == other {
		other = 0x02
	}
	data := map[string]any{
		"Obj":        object.Obj,
		"TypeTag":    fmt.Sprintf("0x%02X", object.TypeTag),
		"OtherTag":   fmt.Sprintf("0x%02X", other),
		"StrhotInit": objmodelgenStrhotCodes[object.Obj+"MngInit"],
		"StrhotGet":  objmodelgenStrhotCodes[object.Obj+"Get"],
		"Set": func(target string, value string) string {
			return strings.NewReplacer("OBJ", target, "VALUE", value).Replace(object.MarkerSet)
		},
		"Get": func(target string) string {
			return strings.NewReplacer("OBJ", target).Replace(object.MarkerGet)
		},
	}
	var buf bytes.Buffer
	buf.WriteString(objmodelgenHeader)
	if err := tmpl.ExecuteTemplate(&buf, name, data); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s %s: %w\n%s", object.Obj, name, err, buf.Bytes())
	}
	return src, nil
}

// objmodelgenTagNames is every named tag in tag order.
func objmodelgenTagNames() []objmodelgenObject {
	names := append(append([]objmodelgenObject{}, objmodelgenObjects...), objmodelgenTagOnlyObjects...)
	sort.Slice(names, func(i, j int) bool { return names[i].TypeTag < names[j].TypeTag })
	return names
}

// objmodelgenTypeTagNameFile is the generated file of package objmodel.
const objmodelgenTypeTagNameFile = "gid_typetagname.go"

// objmodelgenFiles returns every generated file by path.
func objmodelgenFiles(dir string, objmodelDir string) (map[string][]byte, error) {
	tmpl, err := template.New("objmodelgen").Parse(objmodelgenTemplates)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	tags := map[int]string{}
	for _, object := range objmodelgenTagOnlyObjects {
		tags[object.TypeTag] = object.Obj
	}
	for _, object := range objmodelgenObjects {
		if object.TypeTag < 0x01 || object.TypeTag > 0x7F {
			return nil, fmt.Errorf("%s: type tag %#x outside 0x01 to 0x7F", object.Obj, object.TypeTag)
		}
		if previous, ok := tags[object.TypeTag]; ok {
			return nil, fmt.Errorf("%s and %s share type tag %#x", previous, object.Obj, object.TypeTag)
		}
		tags[object.TypeTag] = object.Obj
		base := objmodelgenFileName(object.Obj)
		for suffix, name := range map[string]string{"_gid.go": "gid", "_mng.go": "mng", "_mng_test.go": "test"} {
			src, err := objmodelgenRender(tmpl, name, object)
			if err != nil {
				return nil, err
			}
			files[filepath.Join(dir, base+suffix)] = src
		}
	}
	names, err := template.New("typetagname").Parse(objmodelgenTypeTagNameTemplate)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString(objmodelgenHeader)
	if err := names.Execute(&buf, objmodelgenTagNames()); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s: %w\n%s", objmodelgenTypeTagNameFile, err, buf.Bytes())
	}
	files[filepath.Join(objmodelDir, objmodelgenTypeTagNameFile)] = src
	return files, nil
}

// objmodelgenCheck lists every way dir differs from what would be generated.
// A Def file without a table entry, or a generated file nobody generates
// any more, is a difference too.
func objmodelgenCheck(dir string, files map[string][]byte) ([]string, error) {
	var problems []string
	defs, err := filepath.Glob(filepath.Join(dir, "*_def.go"))
	if err != nil {
		return nil, err
	}
	for _, def := range defs {
		base := strings.TrimSuffix(filepath.Base(def), "_def.go")
		if _, ok := files[filepath.Join(dir, base+"_mng.go")]; !ok {
			problems = append(problems, def+" has no entry in the t0-cx-core-objmodelgen table")
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		name := entry.Name()
		if _, ok := files[filepath.Join(dir, name)]; ok || !strings.HasSuffix(name, ".go") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		if bytes.HasPrefix(bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n")), []byte(objmodelgenHeader)) {
			problems = append(problems, filepath.Join(dir, name)+" is generated but no longer in the table")
		}
	}
	for path, want := range files {
		have, err := os.ReadFile(path)
		if err != nil {
			problems = append(problems, err.Error())
			continue
		}
		if !bytes.Equal(bytes.ReplaceAll(have, []byte("\r\n"), []byte("\n")), want) {
			problems = append(problems, path+" is stale")
		}
	}
	sort.Strings(problems)
	return problems, nil
}

func main() {
	dir := flag.String("dir", "t3-ast", "directory of package ast")
	objmodelDir := flag.String("objmodeldir", "t1-cx-core-objmodel", "directory of package objmodel")
	docsDir := flag.String("docsdir", "docs", "directory of ObjectModel.md and objectmodel-sites.csv")
	root := flag.String("root", ".", "directory whose Go and grammar files hold the site comments")
	check := flag.Bool("check", false, "report stale files instead of writing them")
	flag.Parse()
	files, err := objmodelgenFiles(*dir, *objmodelDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "objmodelgen:", err)
		os.Exit(1)
	}
	docPath := filepath.Join(*docsDir, "ObjectModel.md")
	files[docPath], err = objmodelgenSitesDoc(docPath, filepath.Join(*docsDir, "objectmodel-sites.csv"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "objmodelgen:", err)
		os.Exit(1)
	}
	if *check {
		siteProblems, err := objmodelgenSitesCodeCheck(*root, filepath.Join(*docsDir, "objectmodel-sites.csv"))
		if err != nil {
			fmt.Fprintln(os.Stderr, "objmodelgen:", err)
			os.Exit(1)
		}
		for _, problem := range siteProblems {
			fmt.Println(problem)
		}
		problems, err := objmodelgenCheck(*dir, files)
		if err != nil {
			fmt.Fprintln(os.Stderr, "objmodelgen:", err)
			os.Exit(1)
		}
		for _, problem := range problems {
			fmt.Println(problem)
		}
		if len(problems) > 0 {
			fmt.Println("run make generate-objmodel")
			os.Exit(1)
		}
		if len(siteProblems) > 0 {
			os.Exit(1)
		}
		fmt.Printf("%d generated object model files up to date\n", len(files))
		return
	}
	for path, src := range files {
		if err := os.WriteFile(path, src, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "objmodelgen:", err)
			os.Exit(1)
		}
	}
}
